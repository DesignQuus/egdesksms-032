import { NextResponse } from 'next/server';
import type { NextRequest } from 'next/server';
import { AUTH_COOKIE, INTERNAL_TOKEN_HEADER, isValidInternalToken, verifyAuthToken } from '@/lib/auth';

/**
 * 로그인 없이 호출 가능한 API (고객용 스토어·예약·테이블오더 페이지에서 사용)
 * 형식: [메서드, 경로] — 경로는 정확히 일치해야 함
 */
const PUBLIC_API: ReadonlyArray<readonly [string, string]> = [
  ['POST', '/api/auth/login'],
  ['POST', '/api/auth/logout'],
  ['GET', '/api/products'],
  ['POST', '/api/orders'],
  ['POST', '/api/reservations'],
  ['POST', '/api/coupons/verify'],
];

/** 로그인 없이 접근 가능한 페이지 (페이지 자체에서 권한을 다시 확인하는 /m/* 포함) */
function isPublicPage(pathname: string) {
  return (
    pathname === '/login' ||
    pathname === '/store' || pathname.startsWith('/store/') ||
    pathname === '/table-order' || pathname.startsWith('/table-order/') ||
    pathname === '/booking' || pathname.startsWith('/booking/') ||
    pathname.startsWith('/m/') ||
    pathname.startsWith('/_next/') ||
    pathname === '/favicon.ico' ||
    // public 폴더 정적 파일 (상품 이미지 /uploads/* 등) — 고객 페이지에서 필요
    /\.(png|jpe?g|gif|webp|svg|ico|avif|mp4|webm)$/i.test(pathname)
  );
}



/**
 * EGDesk Database Proxy (Next.js 16+)
 *
 * Intercepts __user_data_proxy, __browser_recording_proxy, __internal_knowledge_proxy, and __ai_center_proxy requests
 * and forwards them to the EGDesk MCP HTTP server. This avoids CORS in local and tunneled environments.
 *
 * Generated by @egdesk/next-api-plugin
 */
export async function proxy(request: NextRequest) {
  const { pathname } = request.nextUrl; // basePath 제외된 경로
  const user = await verifyAuthToken(request.cookies.get(AUTH_COOKIE)?.value);

  // EGDesk 데이터 프록시(DB 전체 읽기/쓰기/삭제 가능)는 로그인한 운영자만 허용
  if (pathname.includes('__') && pathname.includes('_proxy') && !user) {
    return NextResponse.json({ success: false, error: '로그인이 필요합니다.' }, { status: 401 });
  }

  // Intercept __user_data_proxy requests
  if (pathname.includes('__user_data_proxy')) {
    try {
      const body = await request.text();

      // Read API key and URL from environment
      const apiKey = process.env.NEXT_PUBLIC_EGDESK_API_KEY;
      const apiUrl = process.env.NEXT_PUBLIC_EGDESK_API_URL || 'http://localhost:8080';

      const headers: HeadersInit = {
        'Content-Type': 'application/json',
      };

      if (apiKey) {
        headers['X-Api-Key'] = apiKey;
      }

      // Forward to EGDesk MCP server
      const response = await fetch(`${apiUrl}/user-data/tools/call`, {
        method: 'POST',
        headers,
        body,
      });

      const result = await response.json();

      return NextResponse.json(result, { status: response.status });
    } catch (error: any) {
      return NextResponse.json(
        { error: 'Proxy error', message: error.message },
        { status: 500 }
      );
    }
  }

  if (pathname.includes('__browser_recording_proxy')) {
    try {
      const body = await request.text();

      const apiKey = process.env.NEXT_PUBLIC_EGDESK_API_KEY;
      const apiUrl = process.env.NEXT_PUBLIC_EGDESK_API_URL || 'http://localhost:8080';

      const headers: HeadersInit = {
        'Content-Type': 'application/json',
      };

      if (apiKey) {
        headers['X-Api-Key'] = apiKey;
      }

      const response = await fetch(`${apiUrl}/browser-recording/tools/call`, {
        method: 'POST',
        headers,
        body,
      });

      const result = await response.json();

      return NextResponse.json(result, { status: response.status });
    } catch (error: any) {
      return NextResponse.json(
        { error: 'Proxy error', message: error.message },
        { status: 500 }
      );
    }
  }

  if (pathname.includes('__internal_knowledge_proxy')) {
    try {
      const body = await request.text();

      const apiKey = process.env.NEXT_PUBLIC_EGDESK_API_KEY;
      const apiUrl = process.env.NEXT_PUBLIC_EGDESK_API_URL || 'http://localhost:8080';

      const headers: HeadersInit = {
        'Content-Type': 'application/json',
      };

      if (apiKey) {
        headers['X-Api-Key'] = apiKey;
      }

      const response = await fetch(`${apiUrl}/internal-knowledge/tools/call`, {
        method: 'POST',
        headers,
        body,
      });

      const result = await response.json();

      return NextResponse.json(result, { status: response.status });
    } catch (error: any) {
      return NextResponse.json(
        { error: 'Proxy error', message: error.message },
        { status: 500 }
      );
    }
  }

  if (pathname.includes('__ai_center_proxy')) {
    try {
      const body = await request.text();

      const apiKey = process.env.NEXT_PUBLIC_EGDESK_API_KEY;
      const apiUrl = process.env.NEXT_PUBLIC_EGDESK_API_URL || 'http://localhost:8080';

      const headers: HeadersInit = {
        'Content-Type': 'application/json',
      };

      if (apiKey) {
        headers['X-Api-Key'] = apiKey;
      }

      const response = await fetch(`${apiUrl}/ai-center/tools/call`, {
        method: 'POST',
        headers,
        body,
      });

      const result = await response.json();

      return NextResponse.json(result, { status: response.status });
    } catch (error: any) {
      return NextResponse.json(
        { error: 'Proxy error', message: error.message },
        { status: 500 }
      );
    }
  }

  // --- 관리자 인증 제어 로직 ---
  if (pathname.startsWith('/api/')) {
    const isPublic = PUBLIC_API.some(([m, p]) => m === request.method && p === pathname);
    const isInternal = isValidInternalToken(request.headers.get(INTERNAL_TOKEN_HEADER));
    // 최초 설치용: 라우트 내부에서 '운영자 0명 또는 최고관리자'인지 다시 검사
    const isSetup = pathname === '/api/setup-admin' || pathname === '/api/setup';
    if (!isPublic && !isInternal && !isSetup && !user) {
      return NextResponse.json({ success: false, error: '로그인이 필요합니다.' }, { status: 401 });
    }
    return NextResponse.next();
  }

  if (isPublicPage(pathname)) {
    return NextResponse.next();
  }

  // 그 외 관리자 페이지: 유효한 토큰이 없으면 로그인으로 이동 (위조·만료 토큰은 쿠키 삭제)
  if (!user) {
    const loginUrl = request.nextUrl.clone(); // basePath 유지
    loginUrl.pathname = '/login';
    loginUrl.search = '';
    const res = NextResponse.redirect(loginUrl);
    if (request.cookies.get(AUTH_COOKIE)) res.cookies.delete(AUTH_COOKIE);
    return res;
  }

  // Continue to next proxy or route
  return NextResponse.next();
}

export const config = {
  matcher: [
    /*
     * Match all paths except static assets
     * The proxy function filters for __user_data_proxy / __browser_recording_proxy / __internal_knowledge_proxy
     */
    '/:path*',
  ],
};
